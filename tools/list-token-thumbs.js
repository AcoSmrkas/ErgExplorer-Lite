// Writes app/scripts/common/token-thumb-ids.js: the token ids that have a thumbnail in
// app/images/tokens/thumbs. Lite has no icon database, so these local thumbnails are the only icons.
// Run after adding thumbnails: node tools/list-token-thumbs.js
const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, '..', 'app', 'images', 'tokens', 'thumbs');
const ids = Array.from(new Set(fs.readdirSync(dir)
	.map(name => (name.match(/^([0-9a-f]{64})\.webp$/) || [])[1])
	.filter(Boolean))).sort();

fs.writeFileSync(path.join(__dirname, '..', 'app', 'scripts', 'common', 'token-thumb-ids.js'),
	'// Generated by tools/list-token-thumbs.js\nvar TOKEN_THUMB_IDS = ' + JSON.stringify(ids) + ';\n');
console.log(ids.length + ' token thumbnails');
